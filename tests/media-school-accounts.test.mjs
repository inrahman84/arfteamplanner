import test from 'node:test';
import assert from 'node:assert/strict';
import {createMediaDemoStore,resetMediaDemo,loginSchoolDemo,demoMembership} from '../public/media-demo.js';
test('central coordinator provisions school-only login, validates scope and manages access',async()=>{
 resetMediaDemo();
 const central=createMediaDemoStore('demo-central',[{id:'u1',username:'existing_user',name:'Existing User',planner_roles:[]}]);
 const school=createMediaDemoStore('demo-school-a');
 const p={action:'create',display_name:'Demo Creator',username:'demo_creator',school_id:'school-b',password:'DemoOnly1234!'};
 await assert.rejects(school.manageSchoolAccount(p));
 await assert.rejects(central.manageSchoolAccount({...p,school_id:'arf'}));
 await assert.rejects(central.manageSchoolAccount({...p,username:'existing_user'}));
 await assert.rejects(central.manageSchoolAccount({...p,password:'weak'}));
 const a=await central.manageSchoolAccount(p);
 assert.equal(await loginSchoolDemo(p.username,p.password),a.user_id);
 assert.equal(demoMembership(a.user_id).school_id,'school-b');
 await assert.rejects(loginSchoolDemo(p.username,'wrong'));
 await assert.rejects(central.manageSchoolAccount(p));
 const u=createMediaDemoStore(a.user_id);
 assert.ok((await u.rest('media_contents')).every(c=>c.school_id==='school-b'));
 const list=await central.rest('media_school_accounts');
 assert.ok(list.some(x=>x.user_id===a.user_id&&x.username===p.username));
 assert.ok(list.every(x=>!('hash' in x)&&!('password' in x)));
 await assert.rejects(central.manageSchoolAccount({action:'reset',user_id:'demo-manager',password:'AnotherDemo123'}));
 await central.manageSchoolAccount({action:'reset',user_id:a.user_id,password:'AnotherDemo123'});
 await assert.rejects(loginSchoolDemo(p.username,p.password));
 assert.equal(await loginSchoolDemo(p.username,'AnotherDemo123'),a.user_id);
 await central.manageSchoolAccount({action:'revoke',user_id:a.user_id});
 assert.equal(demoMembership(a.user_id),null);
 await assert.rejects(loginSchoolDemo(p.username,'AnotherDemo123'));
 await central.manageSchoolAccount({action:'restore',user_id:a.user_id});
 assert.equal(await loginSchoolDemo(p.username,'AnotherDemo123'),a.user_id);
 const manager=createMediaDemoStore('demo-manager');
 await assert.rejects(manager.rest('media_members','PATCH','?user_id=eq.'+a.user_id,{role:'arf_media_coordinator',school_id:null}));
});
